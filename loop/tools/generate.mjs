#!/usr/bin/env node
/**
 * generate.mjs — Single source of truth -> both modes.
 *
 * Reads:  agents/*.md  (canonical bodies, NO frontmatter)
 *         config/loop.config.json  (tiers, budgets, guardrails)
 * Writes: modes/copilot/   (.github/agents/*.agent.md + prompts + instructions)
 *         modes/agnostic/  (core/*.md + CLAUDE.md + run-pipeline.md)
 *
 * Run:    node tools/generate.mjs
 *
 * Why this exists: "user chooses copilot or agnostic" must NOT mean two
 * hand-maintained copies. Bodies live once in agents/; per-agent model lives
 * once in config. Everything mode-specific is generated. Edit source, regen.
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const cfg = JSON.parse(readFileSync(`${ROOT}/config/loop.config.json`, "utf8"));
const body = (name) => readFileSync(`${ROOT}/agents/${name}.md`, "utf8");
const write = (p, s) => { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, s); };

const AGENTS = ["supervisor","discovery","requirements","adr","lld","story_gen","planning","codegen","testgen","rfc","shadow","review","release"];
const PHASE = {
  discovery:"Discovery", requirements:"Discovery",
  adr:"Design", lld:"Design", story_gen:"Design",
  planning:"Build", codegen:"Build", testgen:"Build", rfc:"Build",
  shadow:"Validate", review:"Validate", release:"Validate"
};
const DESC = {
  supervisor:   "Orchestrates all 4 phases and every agent: phase transitions, story queue, HIL gates, budgets, self-heal, telemetry.",
  discovery:    "Phase 1. Maps stakeholders, consumers, pain points, scope into a discovery brief.",
  requirements: "Phase 1. Converts the discovery brief into functional + non-functional requirements with numbered OIs.",
  adr:          "Phase 2. Produces Architecture Decision Records — options, trade-offs, consequences.",
  lld:          "Phase 2. Produces the versioned Low-Level Design from approved ADRs.",
  story_gen:    "Phase 2. Converts the approved LLD into the dependency-ordered story queue.",
  planning:     "Phase 3. Decomposes one story into planning_context.json. No code, no tests.",
  codegen:      "Phase 3. Generates implementation files from planning_context. Self-heal aware.",
  testgen:      "Phase 3. Generates tests for the story's new files. Self-heal aware.",
  rfc:          "Phase 3. Synthesises a PR description from all prior stage outputs.",
  shadow:       "Phase 4. Diffs the built system against the baseline across a traffic ramp.",
  review:       "Phase 4. Audits Build PRs for security, performance, coverage, standards.",
  release:      "Phase 4. Executes cutover — runbook, rollback plan, retirement milestone."
};
const TOOLS = {
  supervisor:   "['edit','search','runCommands','runTasks']",
  discovery:    "['search','edit']",
  requirements: "['search','edit']",
  adr:          "['search','edit']",
  lld:          "['search','edit']",
  story_gen:    "['search','edit']",
  planning:     "['search','edit']",
  codegen:      "['edit','search','runCommands']",
  testgen:      "['edit','search','runCommands']",
  rfc:          "['edit','search']",
  shadow:       "['search','runCommands','edit']",
  review:       "['search','runCommands','edit']",
  release:      "['edit','search','runCommands']"
};

function resolveModel(mode, agent) {
  const tier = cfg.agent_tiers[agent];
  return cfg.tier_resolution[mode][tier];
}

/* ---------- COPILOT MODE ---------- */
function genCopilot() {
  const base = `${ROOT}/modes/copilot`;
  rmSync(base, { recursive: true, force: true });

  for (const a of AGENTS) {
    const { model } = resolveModel("copilot", a);
    const handoffs = a === "supervisor"
      ? "['discovery','requirements','adr','lld','story_gen','planning','codegen','testgen','rfc','shadow','review','release']"
      : "['supervisor']";
    const fm =
`---
name: ${a}
description: ${DESC[a]}
model: ${model}
tools: ${TOOLS[a]}
handoffs: ${handoffs}
---

`;
    write(`${base}/.github/agents/${a}.agent.md`, fm + body(a));
  }

  // repo-wide instructions
  write(`${base}/.github/copilot-instructions.md`,
`# Copilot Instructions — ${cfg.initiative} Agentic Pipeline

Repo-wide, always-on. Pipeline agents in \`.github/agents/\` inherit these.
Model per agent is set in each agent's frontmatter and was generated from
\`config/loop.config.json\` (tier: ${JSON.stringify(cfg.agent_tiers)}).

Budgets, guardrails, and self-heal are enforced by the supervisor agent.
See \`.github/agents/supervisor.agent.md\`. Invoke with \`/run-pipeline\`.

> Generated by tools/generate.mjs — do not hand-edit. Edit source + regenerate.
`);

  // run-pipeline prompt
  const sup = resolveModel("copilot", "supervisor").model;
  write(`${base}/.github/prompts/run-pipeline.prompt.md`,
`---
mode: agent
description: Run the ${cfg.initiative} agentic pipeline via the supervisor agent.
model: ${sup}
tools: ['edit','search','runCommands','runTasks']
---

# /run-pipeline

Activate the **supervisor** agent and run its loop. Reads
\`config/loop.config.json\`, builds the story queue, and runs
planning -> codegen -> testgen -> rfc per story with HIL gates, budget
enforcement, and self-heal.

Usage:
  /run-pipeline req=${cfg.initiative}
  /run-pipeline req=${cfg.initiative} story=A-01
  /run-pipeline resume
  /run-pipeline req=${cfg.initiative} --max-story-tokens=150000 --spend-cap=8

Commands during the loop: APPROVE | REVISE <feedback> | SKIP | PAUSE | HALT | STATUS
`);
}

/* ---------- AGNOSTIC MODE ---------- */
function genAgnostic() {
  const base = `${ROOT}/modes/agnostic`;
  rmSync(base, { recursive: true, force: true });

  for (const a of AGENTS) {
    const { model, fallback } = resolveModel("agnostic", a);
    const header =
`<!-- MODEL: ${model}  FALLBACK: ${fallback}  (tier: ${cfg.agent_tiers[a]}) -->
<!-- Generated from agents/${a}.md + config/loop.config.json. Do not hand-edit. -->

`;
    write(`${base}/core/${a}.md`, header + body(a));
  }

  // model map the runtime reads
  const map = {};
  for (const a of AGENTS) map[a] = resolveModel("agnostic", a);
  write(`${base}/core/models.json`, JSON.stringify(map, null, 2));

  // CLAUDE.md
  write(`${base}/CLAUDE.md`,
`# CLAUDE.md — ${cfg.initiative} Agentic Pipeline

Auto-loaded project context. Agent prompts live in \`core/\`. Model per agent is
in \`core/models.json\` (generated from config tiers: ${JSON.stringify(cfg.agent_tiers)}).

Runtime is single-provider (Claude Code = Claude family). Per-agent choice is
within the chosen frontier family. Swap the family by editing tier_resolution
in config/loop.config.json and regenerating.

Budgets, guardrails, self-heal, telemetry: enforced by core/supervisor.md.

> Generated by tools/generate.mjs — do not hand-edit. Edit source + regenerate.
`);

  // run-pipeline doc
  write(`${base}/run-pipeline.md`,
`# /run-pipeline (agnostic)

Reads CLAUDE.md, core/supervisor.md, core/models.json, config/loop.config.json,
then loops stories with HIL gates, budgets, and self-heal.

  /run-pipeline req=${cfg.initiative}
  /run-pipeline resume

Commands: APPROVE | REVISE <feedback> | SKIP | PAUSE | HALT | STATUS
`);
}

genCopilot();
genAgnostic();
console.log("Generated modes/copilot and modes/agnostic from single source.");
console.log("Agent tiers:", JSON.stringify(cfg.agent_tiers));
